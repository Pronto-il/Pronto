package com.pronto.ai.eval.taxonomy;

import com.pronto.ai.TestTaxonomy;
import com.pronto.ai.taxonomy.ProfessionTaxonomy;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;
import java.util.stream.Collectors;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The dataset and its splits — the evaluation discipline, asserted rather than trusted.
 *
 * <p>These run offline on every build. They are worth that cost because the failures they catch
 * are invisible at the point they happen and expensive later: a split that drifts between prompt
 * versions makes every A/B comparison meaningless without producing a single error, and a label
 * that no longer exists in the taxonomy makes a case permanently unscoreable while still counting
 * against accuracy.
 */
class TaxonomyDatasetTest {

    private final TaxonomyDataset dataset = TaxonomyDataset.load();
    private final ProfessionTaxonomy taxonomy = TestTaxonomy.taxonomy();

    @Test
    void theDatasetMatchesItsManifest() {
        TaxonomyDataset.Manifest manifest = dataset.manifest();

        assertThat(dataset.cases()).hasSize(5000);
        assertThat(manifest.rows()).isEqualTo(5000);
        assertThat(manifest.professions()).isEqualTo(50);
        assertThat(manifest.subcategories()).isEqualTo(250);
        assertThat(manifest.taxonomyVersion()).isEqualTo(taxonomy.taxonomyVersion());
        // Printed with every run and quoted with every result: without it, an accuracy figure
        // measured against a since-edited dataset cannot be told from one that is still valid.
        assertThat(manifest.datasetSha256()).hasSize(64);
        assertThat(manifest.splitSalt()).isNotBlank();
    }

    /** IDs are the traceability contract back to the workbook — a duplicate would break it. */
    @Test
    void everyCaseKeepsItsOriginalWorkbookIdAndTheyAreUnique() {
        List<Integer> ids = dataset.cases().stream().map(TaxonomyEvaluationCase::id).toList();

        assertThat(ids).doesNotHaveDuplicates();
        assertThat(ids).allSatisfy(id -> assertThat(id).isBetween(1, 5000));
    }

    /**
     * A label the taxonomy does not contain can never be predicted, so the case would count as a
     * permanent failure caused entirely by the dataset. This is the check that keeps the two
     * artefacts — both generated by the same script — actually in step.
     */
    @Test
    void everyLabelResolvesAgainstTheTaxonomy() {
        assertThat(dataset.cases()).allSatisfy(testCase -> {
            assertThat(taxonomy.find(testCase.expectedProfession()))
                    .as("profession of case %d", testCase.id())
                    .isPresent();
            assertThat(taxonomy.findSubcategory(testCase.expectedProfession(), testCase.expectedSubcategory()))
                    .as("case %d: %s is not a subcategory of %s",
                            testCase.id(), testCase.expectedSubcategory(), testCase.expectedProfession())
                    .isPresent();
        });
    }

    /**
     * The dispatch column is derived from the taxonomy, never labelled by hand — so it must agree
     * with the taxonomy exactly. If it drifted, dispatch accuracy would be measured against a
     * stale idea of what Pronto sells.
     */
    @Test
    void theExpectedDispatchCategoryAgreesWithTheTaxonomy() {
        assertThat(dataset.cases()).allSatisfy(testCase ->
                assertThat(testCase.expectedDispatchCategory())
                        .as("dispatch of case %d (%s)", testCase.id(), testCase.expectedProfession())
                        .isEqualTo(taxonomy.dispatchCategoryCode(testCase.expectedProfession())));
    }

    @Test
    void theSplitIsSeventyFifteenFifteen() {
        assertThat(dataset.dev()).hasSize(3500);
        assertThat(dataset.validation()).hasSize(750);
        assertThat(dataset.holdout()).hasSize(750);
        assertThat(dataset.dev().size() + dataset.validation().size() + dataset.holdout().size())
                .isEqualTo(dataset.cases().size());
    }

    /**
     * The splits must not overlap. Stated explicitly because an overlap is the one dataset defect
     * that <em>improves</em> the numbers — a holdout sharing rows with dev would report a prompt
     * as generalising when it had simply memorised.
     */
    @Test
    void theSplitsArePartitionsWithNoSharedCases() {
        Set<Integer> dev = ids(dataset.dev());
        Set<Integer> validation = ids(dataset.validation());
        Set<Integer> holdout = ids(dataset.holdout());

        assertThat(dev).doesNotContainAnyElementsOf(validation);
        assertThat(dev).doesNotContainAnyElementsOf(holdout);
        assertThat(validation).doesNotContainAnyElementsOf(holdout);
    }

    /**
     * Every (profession, subcategory) group appears in all three splits.
     *
     * <p>Stratification is why the split is applied within groups rather than across the dataset:
     * a global 15% sample would leave whole professions out of validation, and per-profession
     * accuracy on that split would then be undefined rather than merely noisy.
     */
    @Test
    void everyGroupIsRepresentedInAllThreeSplits() {
        Map<String, List<TaxonomyEvaluationCase>> devGroups = groupBy(dataset.dev());
        Map<String, List<TaxonomyEvaluationCase>> validationGroups = groupBy(dataset.validation());
        Map<String, List<TaxonomyEvaluationCase>> holdoutGroups = groupBy(dataset.holdout());

        assertThat(devGroups).hasSize(250);
        assertThat(validationGroups).hasSize(250);
        assertThat(holdoutGroups).hasSize(250);

        devGroups.forEach((group, cases) -> assertThat(cases).as("dev group %s", group).hasSize(14));
        validationGroups.forEach((group, cases) -> assertThat(cases).hasSize(3));
        holdoutGroups.forEach((group, cases) -> assertThat(cases).hasSize(3));
    }

    /**
     * <b>The split is frozen data, not a runtime computation.</b>
     *
     * <p>This is what makes "V2 scored better than V1 on validation" a comparison rather than a
     * coincidence: the assignment is read from the file, so it cannot vary with prompt version,
     * taxonomy version, JVM, locale or iteration order. Re-loading and re-comparing is a cheap
     * proxy for that guarantee — if anything ever derived the split at load time, this fails.
     */
    @Test
    void splitAssignmentIsStableAcrossReloads() {
        Map<Integer, String> first = splitById(TaxonomyDataset.load());
        Map<Integer, String> second = splitById(TaxonomyDataset.load());

        assertThat(second).isEqualTo(first);
        assertThat(first).hasSize(5000);
    }

    @Test
    void aStratifiedSampleKeepsEveryGroupAndIsDeterministic() {
        List<TaxonomyEvaluationCase> first = TaxonomyDataset.stratifiedSample(dataset.dev(), 2);
        List<TaxonomyEvaluationCase> second = TaxonomyDataset.stratifiedSample(dataset.dev(), 2);

        assertThat(first).hasSize(500);
        assertThat(groupBy(first)).hasSize(250);
        // Same input, same output -- a smoke run must be comparable with the one before it.
        assertThat(ids(second)).isEqualTo(ids(first));
    }

    @Test
    void splitOrDefaultFallsBackToDevSoTuningNeverTouchesHoldoutByAccident() {
        assertThat(TaxonomyDataset.splitOrDefault(null)).isEqualTo(TaxonomyEvaluationCase.SPLIT_DEV);
        assertThat(TaxonomyDataset.splitOrDefault("")).isEqualTo(TaxonomyEvaluationCase.SPLIT_DEV);
        assertThat(TaxonomyDataset.splitOrDefault(" HOLDOUT ")).isEqualTo(TaxonomyEvaluationCase.SPLIT_HOLDOUT);
    }

    private static Set<Integer> ids(List<TaxonomyEvaluationCase> cases) {
        return cases.stream().map(TaxonomyEvaluationCase::id).collect(Collectors.toCollection(
                java.util.LinkedHashSet::new));
    }

    private static Map<String, List<TaxonomyEvaluationCase>> groupBy(List<TaxonomyEvaluationCase> cases) {
        return cases.stream().collect(Collectors.groupingBy(
                testCase -> testCase.expectedProfession() + "/" + testCase.expectedSubcategory()));
    }

    private static Map<Integer, String> splitById(TaxonomyDataset dataset) {
        return dataset.cases().stream().collect(Collectors.toMap(
                TaxonomyEvaluationCase::id, TaxonomyEvaluationCase::split,
                (a, b) -> a, java.util.LinkedHashMap::new));
    }

    private static <T> Function<T, T> identity() {
        return Function.identity();
    }
}
